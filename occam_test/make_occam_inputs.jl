# make_occam_inputs.jl -- turn the two Occam models into the shapes stages 3-6
# already expect, so those stages run UNMODIFIED.
#
#   julia --project=. occam_test/make_occam_inputs.jl <TAG>
#
# An Occam result is one model; stages 3, 4 and 5 consume posterior ensembles.
# Rather than teach every stage about deterministic input, the single model is
# written as a one-draw ensemble. The percentiles the stages compute then
# collapse onto that model, which is the honest reading of a deterministic
# inversion: there is no posterior, so p05 = p50 = p95.
#
# Writes, per column:
#   data/cond_C2_occam<TAG>.jld2       one-draw SNMR ensemble  (stage 3, stage 4 floor)
#   data/aem_draws_occam<TAG>.jld2     one-draw AEM sigma      (stage 5)
#   configs/occam_<TAG>.toml           the site config, repointed at both
#
# Nothing here touches cond_C2_typical*, aem_draws_2M or outputs/synth_*.
using JLD2, Printf

const HERE = normpath(@__DIR__)
const ROOT = normpath(joinpath(HERE, ".."))
const OUT  = joinpath(ROOT, "data")
const TAG  = length(ARGS) >= 1 ? ARGS[1] : error("need a tag, e.g. 2P")

smrf = joinpath(OUT, "smr_occam$(TAG).jld2")
aemf = joinpath(OUT, "aem_occam$(TAG).jld2")
for f in (smrf, aemf)
    isfile(f) || error("missing $f -- run tools/quicklook.jl $TAG first")
end
S = load(smrf); A = load(aemf)

θ = collect(Float64, S["θ_occam"]); zsmr = collect(Float64, S["zsmr"])
σ = collect(Float64, A["σ_occam"]); zall = collect(Float64, A["zall_aem"])
@printf("tag %s: theta %d cells to %.1f m ; sigma %d cells to %.1f m\n",
        TAG, length(θ), zsmr[end], length(σ), zall[end])
@printf("  SNMR chi2/N %.3f ; AEM chi2/N %.3f\n",
        S["chi2"]/S["ndata"], A["chi2"]/A["ndata"])

condf = joinpath(OUT, "cond_C2_occam$(TAG).jld2")
jldsave(condf;
    ens = [reshape(Float32.(θ), length(θ), 1)],   # ONE draw, the Occam model
    cond = "C2", tier = "occam", islog = true,
    kernel = "AEM_occam", nsamples = 1, zsmr = zsmr,
    note = "one-draw ensemble from a deterministic Occam inversion; " *
           "no posterior, so every percentile equals the model")
println("  wrote ", relpath(condf, ROOT))

drawf = joinpath(OUT, "aem_draws_occam$(TAG).jld2")
jldsave(drawf;
    zall_aem = zall, sigma = reshape(σ, length(σ), 1),
    draw_ix = [1], ndraws_total = 1, seed = 0,
    note = "one-draw AEM sigma from a deterministic Occam inversion")
println("  wrote ", relpath(drawf, ROOT))

# The site config, copied wholesale rather than chained through `extends`, so
# this does not depend on the loader supporting a second level of inheritance.
src = joinpath(ROOT, "configs", "synth_$(TAG).toml")
isfile(src) || error("no site config at $src")
t = read(src, String)
subs = [
    ("name  = \"synth_$(TAG)\"",                  "name  = \"occam_$(TAG)\""),
    ("snmr_ensemble = \"data/cond_C2_typical$(TAG)T.jld2\"",
     "snmr_ensemble = \"data/cond_C2_occam$(TAG).jld2\""),
    ("dir = \"outputs/synth_$(TAG)\"",            "dir = \"outputs/occam_$(TAG)\""),
]
for (a, b) in subs
    count(a, t) == 1 || error("expected exactly one occurrence of:\n  $a\nin $src (found $(count(a, t)))")
    t = replace(t, a => b)
end
# stage1_draws differs per column (2P points at aem_draws_2M, deliberately), so
# it is rewritten by pattern rather than by literal.
m = match(r"stage1_draws = \"[^\"]+\"", t)
m === nothing && error("no stage1_draws key in $src")
t = replace(t, m.match => "stage1_draws = \"data/aem_draws_occam$(TAG).jld2\"")
t = replace(t, "#  synth_$(TAG).toml" => "#  occam_$(TAG).toml  (generated by occam_test/make_occam_inputs.jl)")
cfg = joinpath(ROOT, "configs", "occam_$(TAG).toml")
write(cfg, t)
println("  wrote ", relpath(cfg, ROOT))
